#ifndef MALLOC_H
#define MALLOC_H

#include <stddef.h>

// /*
//                                  Format of an allocated memory block
//     +---------------------------------------------------------------------------------------+
//     |                                     64-bits wide                                      |
//     +---------------------------------------------------------------------------------------+
//
//     +-----------------------------------------------------------------------------+---------+ <- header
//     |                                  block_size                                 |  alloc  |
//     |                           (1 LSB implicitly 0)                              |   (1)   |
//     |                                    64 bits                                  |  1 bit  |
//     +-----------------------------------------------------------------------------+---------+ <- (aligned)
//     |                                                                                       |
//     |                                 Payload and Padding                                   |
//     |                                   (N Memory Rows)                                     |
//     |                                                                                       |
//     |                                                                                       |
//     +-----------------------------------------------------------------------------+---------+ <- footer
//     |                                  block_size                                 |  alloc  |
//     |                           (1 LSB implicitly 0)                              |   (1)   |
//     |                                    64 bits                                  |  1 bit  |
//     +-----------------------------------------------------------------------------+---------+
//
//
//                                      Format of a free memory block
//     +-----------------------------------------------------------------------------+---------+ <- header
//     |                                  block_size                                 |  alloc  |
//     |                           (1 LSB implicitly 0)                              |   (0)   |
//     |                                    64 bits                                  |  1 bit  |
//     +-----------------------------------------------------------------------------+---------+ <- (aligned)
//     |                                                                                       |
//     |                              Pointer to next free block                               |
//     |                                                                                       |
//     +---------------------------------------------------------------------------------------+
//     |                                                                                       |
//     |                             Pointer to previous free block                            |
//     |                                                                                       |
//     +---------------------------------------------------------------------------------------+
//     |                                                                                       |
// 										..........
// 	|                                                                                       |
//     +-----------------------------------------------------------------------------+---------+ <- footer
//     |                                  block_size                                 |  alloc  |
//     |                           (1 LSB implicitly 0)                              |   (0)   |
//     |                                    64 bits                                  |  1 bit  |
//     +-----------------------------------------------------------------------------+---------+
// */
//

void* malloc(size_t size);
void free(void* ptr);

#endif
